import fs from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = "contracts/grading-agent/prompt-injection-rules.json";
const { rules } = JSON.parse(fs.readFileSync(path.join(root, source), "utf8"));
// 三种运行时只消费生成规则；修改规则后必须重跑本脚本，CI --check 拒绝任意一份漂移。
const header = `Generated from ${source}; run node scripts/sync-prompt-injection-rules.mjs.`;
const js = `// ${header}\nexport const promptInjectionRules = ${JSON.stringify(rules, null, 2)};\n`;
const py = `# ${header}\nINJECTION_RULES = ${JSON.stringify(rules, null, 2)}\n`;
const quote = value => JSON.stringify(value);
const go = `// Code generated by scripts/sync-prompt-injection-rules.mjs; DO NOT EDIT.\npackage subjective\n\nvar promptInjectionRules = []promptInjectionRule{\n${rules.map(rule => `\t{signal: ${quote(rule.gateway_signal)}, pattern: ${quote(rule.pattern)}, orderedTerms: []string{${(rule.ordered_terms ?? []).map(quote).join(", ")}}},`).join("\n")}\n}\n`;
const outputs = {
  "lab/src/guardrails/promptInjectionRules.generated.js": js,
  "ai-services/grading_agent/prompt_injection_rules_generated.py": py,
  "services/api-gateway/internal/subjective/prompt_injection_rules_generated.go": go
};
for (const [relative, content] of Object.entries(outputs)) {
  const target = path.join(root, relative);
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== content) throw new Error(`Prompt injection rules are stale: ${relative}`);
  } else fs.writeFileSync(target, content);
}
